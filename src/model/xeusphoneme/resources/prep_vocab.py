def dump_vocab(path):
    vocab = {"<blank>": 0, "<sos>": 1, "<eos>": 2, "<unk>": 3}
    for _, tok in enumerate(IPAPACK_VOCABULARY):
        newidx = len(vocab)
        vocab[tok] = newidx

    with open(path, "w") as f:
        json.dump(vocab, f, ensure_ascii=False, indent=2)
    print(f"Dumped vocab of size {len(vocab)} to {path}")


def read_vocab(path):
    with open(path, "r") as f:
        vocab = json.load(f)
    return vocab


